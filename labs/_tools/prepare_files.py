def wcsv(path, header, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        cw = csv.writer(f, lineterminator='\n')
        cw.writerow(header)
        cw.writerows(rows)


